-- Runs against a real daemon: no mocked editor or transport.
local root = assert(vim.env.II_ROOT)
vim.opt.runtimepath:append(root .. '/plugins/ii.nvim')
local ii = require('ii')
ii.setup({ executable = root .. '/target/debug/ii', socket_path = assert(vim.env.II_SOCKET), debounce_ms = 5 })
local function ready(win)
  assert(vim.wait(10000, function()
    local status = ii.status(win)
    return not status.pending and status.source_tick ~= nil
  end, 10), 'render did not finish: ' .. vim.inspect(ii.status(win)))
end
vim.cmd.edit(root .. '/showcase/scenarios/incident.md')
vim.bo.filetype = 'markdown'
local buf = vim.api.nvim_get_current_buf()
local left = vim.api.nvim_get_current_win()
ii.render(buf, left)
ready(left)
assert(ii.status(left).placements >= 8, 'missing formula placements')
local tick = ii.status(left).source_tick
vim.cmd('normal! 500Gzt')
vim.cmd.redraw()
assert(ii.status(left).source_tick == tick, 'scroll unexpectedly changed source snapshot')
vim.cmd.vsplit()
local right = vim.api.nvim_get_current_win()
vim.api.nvim_win_set_width(right, 24)
ii.render(buf, right)
ready(right)
assert(ii.status(right).cols < ii.status(left).cols, 'split geometry was shared')
vim.api.nvim_buf_set_lines(buf, 0, 1, false, {'# Updated while rendering'})
for _ = 1, 5 do ii.render(buf, right) end
ready(right)
assert(ii.status(right).source_tick == vim.api.nvim_buf_get_changedtick(buf), 'stale result accepted')
ii.toggle(buf)
assert(ii.status(right).placements == 0 and not ii.status(right).pending, 'toggle leaked a request')
ii.toggle(buf)
ready(right)
assert(ii.status(right).placements >= 8)
ii.clear(buf)
assert(ii.status(left).placements == 0 and ii.status(right).placements == 0)
vim.cmd('qa!')
